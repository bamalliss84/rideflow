    for key, values in S.items():
        out[key] = values[index]
        if index == 0 and key in PLACEHOLDERS:
            out["@" + key] = {"placeholders": {p: {"type": "String"} for p in PLACEHOLDERS[key]}}
    (root / f"app_{lang}.arb").write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
